const clipFetches = new Set();
// Only the app shell and its public libraries are cached. Account, profile and sync traffic must always hit the network.
const CACHEABLE_HOSTS = ['fonts.googleapis.com', 'fonts.gstatic.com'];
// Le code de l'app (HTML, JS, CSS, manifeste) : réseau d'abord, pour ne jamais mélanger deux versions après un déploiement.
const isAppCode = url => url.origin === self.location.origin && /\.(js|css|json|html)$|\/$/.test(url.pathname) && !url.pathname.startsWith('/media/') && !url.pathname.startsWith('/vendor/');
const isMedia = u => u.includes('/media/') && !/\.(css|woff2|ttf|json|md)$/.test(u);
// Ne jamais lancer des dizaines de Mo de téléchargement quand l'utilisateur économise ses données.
const saveData = () => !!(self.navigator && navigator.connection && (navigator.connection.saveData || /(^|-)2g$/.test(navigator.connection.effectiveType || '')));

// Par lots : une rafale de centaines de requêtes simultanées sature le réseau d'un téléphone.
async function cacheInBatches(list, size) {
  const c = await caches.open(CACHE);
  for (let i = 0; i < list.length; i += size) {
    await Promise.all(list.slice(i, i + size).map(async u => {
      if (await c.match(u)) return;
      return c.add(u).catch(() => null);
    }));
  }
}

self.addEventListener('install', e => {
  // Le socle part d'un coup : l'app doit être contrôlée au plus vite.
  // Le socle est atomique : si un fichier de code manque, l'installation échoue et l'ancienne version reste active.
  // Seules les illustrations peuvent manquer sans bloquer.
  const core = PRECACHE.filter(u => !isMedia(u)), media = PRECACHE.filter(isMedia);
  e.waitUntil(
    caches.open(CACHE).then(c =>
      c.addAll(core.map(u => new Request(u, {cache: 'reload'})))
        .then(() => Promise.all(media.map(u => c.add(u).catch(() => null))))
    ).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys().then(keys =>
      Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))
    ).then(() => self.clients.claim()).then(() => saveData() ? null : cacheInBatches(PRECACHE_MEDIA, 12))
  );
});

// Navigation et code : réseau d'abord. Médias, polices et bibliothèques : cache avec mise à jour en arrière-plan.
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  const sameOrigin = url.origin === self.location.origin;
  if (!sameOrigin && !CACHEABLE_HOSTS.includes(url.hostname)) return;
  if (sameOrigin && url.pathname.startsWith('/api/')) return;

  // Native video players request byte ranges, including when seeking offline.
  if (e.request.headers.has('range') && /\.(mp4|webm)$/i.test(url.pathname)) {
    e.respondWith((async () => {
      const cached = await caches.match(e.request.url);
      if (!cached || cached.status !== 200) {
        // Extraits du QI vidéo : la première lecture passe par le réseau, le fichier entier est gardé pour les suivantes.
        if (sameOrigin && url.pathname.startsWith('/clips/') && !clipFetches.has(url.href)) {
          clipFetches.add(url.href);
          e.waitUntil(fetch(url.href).then(res => res.ok ? caches.open(CACHE).then(c => c.put(url.href, res)) : null).catch(() => {}).finally(() => clipFetches.delete(url.href)));
        }
        return fetch(e.request);
      }
      const buffer = await cached.arrayBuffer(), size = buffer.byteLength;
      const range = /^bytes=(\d*)-(\d*)$/.exec(e.request.headers.get('range'));
      if (!range || (!range[1] && !range[2])) return new Response(null, {status:416,headers:{'Content-Range':`bytes */${size}`}});
      const start = range[1] ? Number(range[1]) : Math.max(0,size-Number(range[2]));
      const end = range[1] && range[2] ? Math.min(size-1,Number(range[2])) : size-1;
      if (!Number.isSafeInteger(start) || !Number.isSafeInteger(end) || start> end || start>=size) return new Response(null, {status:416,headers:{'Content-Range':`bytes */${size}`}});
      return new Response(buffer.slice(start,end+1), {status:206,headers:{'Content-Type':cached.headers.get('Content-Type')||'video/mp4','Content-Length':String(end-start+1),'Content-Range':`bytes ${start}-${end}/${size}`,'Accept-Ranges':'bytes'}});
    })());
    return;
  }

  if (e.request.mode === 'navigate') {
    e.respondWith(
      fetch(e.request).then(res => {
        // Une page d'erreur (404, 500, portail Wi-Fi) ne doit jamais remplacer l'app hors connexion.
        if (res.ok && res.type === 'basic') {
          const clone = res.clone();
          caches.open(CACHE).then(c => c.put('./index.html', clone));
        }
        return res;
      }).catch(async () => {
        const cached = await caches.match('./index.html');
        if (!cached) return Response.error();
        // Static hosts can redirect /index.html to /. A redirected cached response
        // cannot satisfy a navigation in manual redirect mode, so rebuild it.
        return new Response(await cached.arrayBuffer(), {
          status: cached.status, statusText: cached.statusText, headers: cached.headers
        });
      })
    );
    return;
  }

  if (isAppCode(url)) {
    e.respondWith(
      fetch(e.request).then(res => {
        if (res.ok) {
          const clone = res.clone();
          caches.open(CACHE).then(c => c.put(e.request, clone));
        }
        return res;
      }).catch(async () => (await caches.match(e.request)) || Response.error())
    );
    return;
  }

  e.respondWith(
    caches.match(e.request).then(cached => {
      const fresh = fetch(e.request).then(res => {
        if (res && (res.status === 200 || res.type === 'opaque')) {
          const clone = res.clone();
          caches.open(CACHE).then(c => c.put(e.request, clone));
        }
        return res;
      }).catch(() => cached);
      return cached || fresh;
    })
  );
});
